META_FILES = ["stdout.log", "stderr.log", "exit_code", "started", "finished", "job.sh"]


def new_run_id() -> str:
    return datetime.now().strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(2)


def render_script(spec: JobSpec, cluster: Cluster, res: Resources, run_dir: str, image: str) -> str:
    sched = get_scheduler(cluster.scheduler)
    q = shlex.quote
    binds = [run_dir, *spec.binds]
    launcher = spec.launcher or (cluster.launcher if spec.mpi else "")
    exec_cmd = f'apptainer exec -B "$REANNX_BINDS" "$REANNX_IMAGE" {shlex.join(spec.command)}'
    lines = ["#!/bin/bash", *sched.directives(spec, res, cluster, run_dir), "",
             "# generated by reannx", "set -u",
             f"RUN_DIR={q(run_dir)}", f"export REANNX_IMAGE={q(image)}",
             f"export REANNX_BINDS={q(','.join(binds))}",
             'mkdir -p "$RUN_DIR/work" && cd "$RUN_DIR/work" || exit 98',
             'date -u +%FT%TZ > "$RUN_DIR/started"']
    if cluster.modules:
        lines.append("module purge; module load " + " ".join(cluster.modules))
    lines += [f"export {k}={q(str(v))}" for k, v in spec.env.items()]
    if spec.setup:
        lines += ["", "# --- setup (from job spec) ---", *spec.setup, "# --- end setup ---", ""]
    lines += ["set +e", f"{launcher} {exec_cmd}".strip(), "rc=$?",
              'echo $rc > "$RUN_DIR/exit_code"; date -u +%FT%TZ > "$RUN_DIR/finished"', "exit $rc", ""]
    return "\n".join(lines)


def _image_plan(spec: JobSpec, root: str) -> tuple[str, str, Path | None]:
    """-> (remote image path, kind, local file to upload or None)."""
    img = spec.image
    if img.startswith("remote:"):
        return img[7:], "remote", None
    if re.match(r"^(docker|oras|library|shub)://", img):
        return f"{root}/images/{re.sub(r'[^A-Za-z0-9._-]', '_', img.split('://', 1)[1])}.sif", "pull", None
    p = Path(img).expanduser()
    if not p.is_absolute():
        p = spec.base_dir / p
    if p.is_file():
        h = hashlib.sha256()
        with p.open("rb") as f:
            for chunk in iter(lambda: f.read(1 << 22), b""):
                h.update(chunk)
        return f"{root}/images/{p.stem}-{h.hexdigest()[:12]}.sif", "upload", p
    if os.path.isabs(img):
        return img, "remote", None            # absolute path not on the laptop: assume on the cluster
    raise ConfigError(f"image {img!r}: no such local file (use remote:/path, docker://… or a local .sif)")


@dataclass
class Plan:
    run_id: str
    cluster: Cluster
    res: Resources
    run_dir: str
    root: str
    image: str
    image_kind: str
    image_local: Path | None
    script: str
    steps: list[str] = field(default_factory=list)


def make_plan(spec: JobSpec, cluster: Cluster, run_id: str | None = None) -> Plan:
    spec.check()
    res = cluster.validate(spec.resources)
    root = cluster.remote_root(res.account)
    rid = run_id or new_run_id()
    run_dir = f"{root}/runs/{rid}"
    image, kind, local = _image_plan(spec, root)
    script = render_script(spec, cluster, res, run_dir, image)
    steps = [f"mkdir -p {run_dir}/work {root}/images"]
    steps += {"upload": [f"upload {local} -> {image} (skipped if present)"],
              "pull": [f"apptainer pull {image} {spec.image} (skipped if present)"],
              "remote": [f"use image on cluster: {image}"]}[kind]
    steps += [f"copy input {i} -> {run_dir}/work/" for i in spec.inputs]
    steps += [f"write {run_dir}/job.sh", get_scheduler(cluster.scheduler).submit_cmd(run_dir)]
    return Plan(rid, cluster, res, run_dir, root, image, kind, local, script, steps)


def transport_for(cluster: Cluster) -> Transport:
    return Transport(cluster.ssh_host)


def submit(spec: JobSpec, cluster: Cluster, out_dir: Path, log=print) -> dict:
    plan = make_plan(spec, cluster)
    tr, sched = transport_for(cluster), get_scheduler(cluster.scheduler)
    q = shlex.quote
    log(f"[{plan.run_id}] preparing {plan.run_dir}")
    tr.run(f"mkdir -p {q(plan.run_dir)}/work {q(plan.root)}/images")
    if plan.image_kind == "upload":
        if tr.run(f"test -f {q(plan.image)} && echo y || echo n").strip() == "n":
            log(f"[{plan.run_id}] uploading image {plan.image_local.name} …")
            tr.put_file(plan.image_local, plan.image + ".part")
            tr.run(f"mv {q(plan.image + '.part')} {q(plan.image)}")
    elif plan.image_kind == "pull":
        log(f"[{plan.run_id}] ensuring image {spec.image} on cluster …")
        tr.run(f"test -f {q(plan.image)} || apptainer pull {q(plan.image + '.part')} {q(spec.image)} "
               f"&& mv {q(plan.image + '.part')} {q(plan.image)}")
    else:
        tr.run(f"test -f {q(plan.image)}")      # fail early if the image path is wrong
    for i in spec.inputs:
        tr.put(spec.base_dir, i, f"{plan.run_dir}/work")
    tr.write_file(f"{plan.run_dir}/job.sh", plan.script, "755")
    job_id = sched.parse_job_id(tr.run(sched.submit_cmd(q(plan.run_dir))))
    run = {"id": plan.run_id, "name": spec.name, "cluster": cluster.name, "ssh_host": cluster.ssh_host,
           "scheduler": cluster.scheduler, "job_id": job_id, "run_dir": plan.run_dir,
           "outputs": spec.outputs, "out_dir": str(out_dir / plan.run_id),
           "submitted": datetime.now().isoformat(timespec="seconds"), "state": State.PENDING.value}
    state.save(run)
    log(f"[{plan.run_id}] submitted as job {job_id} on {cluster.name}")
    return run


def _tr(run: dict) -> Transport:
    return Transport(run["ssh_host"])


def status(run: dict, save: bool = True) -> tuple[State, dict]:
    sched = get_scheduler(run["scheduler"])
    out = _tr(run).run(f"{sched.status_cmd(run['job_id'])}; echo '@@RC'; cat {shlex.quote(run['run_dir'])}/exit_code 2>/dev/null",
                       check=False)
    sched_out, _, rc = out.rpartition("@@RC")
    st, info = sched.parse_status(sched_out)
    rc = rc.strip()
    if rc.lstrip("-").isdigit():
        info["exit"] = rc
        if st in (State.UNKNOWN, State.RUNNING, State.PENDING, State.COMPLETED, State.FAILED):
            st = State.COMPLETED if int(rc) == 0 else State.FAILED   # our own sentinel wins
    if save and st.value != run.get("state"):
        run["state"] = st.value
        state.save(run)
    return st, info


def logs(run: dict, which: str = "stdout", offset: int = 0) -> str:
    f = shlex.quote(f"{run['run_dir']}/{which}.log")
    return _tr(run).run(f"tail -c +{offset + 1} {f} 2>/dev/null", check=False)


def wait(run: dict, poll: float = 10, follow: bool = False, log=print, sleep=time.sleep) -> State:
    last, off = None, 0
    while True:
        st, info = status(run)
        if st != last:
            log(f"[{run['id']}] {st.value} {info.get('elapsed', '')}".rstrip())
            last = st
        if follow:
            chunk = logs(run, "stdout", off)
            if chunk:
                print(chunk, end="", flush=True)
                off += len(chunk.encode())
        if st.terminal:
            return st
        sleep(poll)


def fetch(run: dict, out: Path | None = None) -> Path:
    out = Path(out or run["out_dir"])
    tr = _tr(run)
    tr.get(f"{run['run_dir']}/", out, "--exclude=/work/")
    if run["outputs"]:
        args = ["--prune-empty-dirs", "--include=*/", *[f"--include={p}" for p in run["outputs"]], "--exclude=*"]
        tr.get(f"{run['run_dir']}/work/", out / "work", *args)
    return out


def cancel(run: dict):
    _tr(run).run(get_scheduler(run["scheduler"]).cancel_cmd(run["job_id"]))


def clean(run: dict):
    _tr(run).run(f"rm -rf {shlex.quote(run['run_dir'])}")
